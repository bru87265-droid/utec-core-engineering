#!/usr/bin/env python3

# Definición de variables cumpliendo las restricciones
language = "Python"
version = 3
pi_approx = 22 / 7  # Derivado de un valor numérico
computation_valid = 10 > 5  # Resultado de evaluar una expresión de comparación

# Impresión exacta utilizando f-strings (interpolación de cadenas)
print(f"Language: {language}")
print(f"Version: {version}")
print(f"Pi approx: {pi_approx:.2f}")  # Formateado a exactamente dos decimales
print(f"Computation valid: {computation_valid}")
